// Étape 2/2 : lit lineage_rows.json / spell_rows.json (produits par
// extract-race-lineages-data.mjs, dans le répertoire courant) et écrit
// lot3_migration.sql (corps `create table` + `do $$` d'insertion) dans le
// répertoire courant. Voir extract-race-lineages-data.mjs pour l'étape 1.

import fs from 'node:fs';

const lineageRows = JSON.parse(fs.readFileSync('lineage_rows.json', 'utf-8'));
const spellRows = JSON.parse(fs.readFileSync('spell_rows.json', 'utf-8'));

function lit(s) {
  if (s === null || s === undefined) return 'null';
  return '$q$' + String(s).split('$q$').join('') + '$q$';
}
function litOrNull(s) { return s === null || s === undefined ? 'null' : lit(s); }

const lines = [];

lines.push('-- Chantier "Personnages" (app mobile) -- contenu D&D, lot 3.');
lines.push('-- Nouvelles tables public.race_lineages et public.racial_innate_spells, absentes du');
lines.push('-- schéma existant (rien ne représentait jusqu\'ici le concept "lignée/ascendance" -- ex.');
lines.push('-- couleur de dragon du Drakéide -- ni "cette race/sous-race accorde tel sort inné à tel');
lines.push('-- niveau"). Contenu issu de race_lineages.json / racial_innate_spells.json, déjà');
lines.push('-- reformulé légalement par la source (résumés mécaniques originaux pour le hors-SRD),');
lines.push('-- donc pas de besoin de relecture différée comme le lot 4.');
lines.push('--');
lines.push('-- 2 entrées de race_lineages.json (drakéide chromatique/diamantin Fizban\'s, gap de');
lines.push('-- données documenté explicitement "Ne pas utiliser tel quel" par la source) sont');
lines.push('-- ignorées. 1 entrée de racial_innate_spells.json (Aasimar) est ignorée car sa race');
lines.push('-- n\'est pas en base (traits non rédigés, voir lot "brouillon" -- scripts/');
lines.push('-- class_features_non_srd_draft.json). 9 lignes de racial_innate_spells sur 36 ont un');
lines.push('-- spell_id volontairement NULL (8 sorts introuvables dans public.spells au moment de');
lines.push('-- cette migration -- Lumières dansantes, Lueurs féeriques, Illusion mineure, Flammes,');
lines.push('-- Grande foulée -- + le choix libre du Haut-elfe, jamais un sort fixe) : explication');
lines.push('-- dans public.translations (entity_type = \'racial_innate_spell\', field_name =');
lines.push('-- \'unresolved_note\'), voir le rapport de tâche pour le détail.');
lines.push('');
lines.push('create table public.race_lineages (');
lines.push('  id int generated always as identity primary key,');
lines.push('  race_id int not null references public.races (id) on delete cascade,');
lines.push('  subrace_id int references public.subraces (id) on delete cascade,');
lines.push('  lineage_group text not null,');
lines.push('  grants_ability_bonus boolean not null default false,');
lines.push('  ability_bonuses jsonb,');
lines.push('  damage_type text,');
lines.push('  resistance_damage_type text,');
lines.push('  source_book text');
lines.push(');');
lines.push('');
lines.push('alter table public.race_lineages enable row level security;');
lines.push('');
lines.push('create policy "Authenticated users can read race_lineages"');
lines.push('  on public.race_lineages for select');
lines.push('  to authenticated');
lines.push('  using (true);');
lines.push('');
lines.push('create policy "Admins can insert race_lineages"');
lines.push('  on public.race_lineages for insert');
lines.push('  to authenticated');
lines.push('  with check (public.is_admin());');
lines.push('');
lines.push('create policy "Admins can update race_lineages"');
lines.push('  on public.race_lineages for update');
lines.push('  to authenticated');
lines.push('  using (public.is_admin())');
lines.push('  with check (public.is_admin());');
lines.push('');
lines.push('create policy "Admins can delete race_lineages"');
lines.push('  on public.race_lineages for delete');
lines.push('  to authenticated');
lines.push('  using (public.is_admin());');
lines.push('');
lines.push('create table public.racial_innate_spells (');
lines.push('  id int generated always as identity primary key,');
lines.push('  race_id int not null references public.races (id) on delete cascade,');
lines.push('  subrace_id int references public.subraces (id) on delete cascade,');
lines.push('  lineage_id int references public.race_lineages (id) on delete cascade,');
lines.push('  spell_id int references public.spells (id) on delete set null,');
lines.push('  character_level int not null,');
lines.push('  ability_used_for_dc text not null');
lines.push(');');
lines.push('');
lines.push('alter table public.racial_innate_spells enable row level security;');
lines.push('');
lines.push('create policy "Authenticated users can read racial_innate_spells"');
lines.push('  on public.racial_innate_spells for select');
lines.push('  to authenticated');
lines.push('  using (true);');
lines.push('');
lines.push('create policy "Admins can insert racial_innate_spells"');
lines.push('  on public.racial_innate_spells for insert');
lines.push('  to authenticated');
lines.push('  with check (public.is_admin());');
lines.push('');
lines.push('create policy "Admins can update racial_innate_spells"');
lines.push('  on public.racial_innate_spells for update');
lines.push('  to authenticated');
lines.push('  using (public.is_admin())');
lines.push('  with check (public.is_admin());');
lines.push('');
lines.push('create policy "Admins can delete racial_innate_spells"');
lines.push('  on public.racial_innate_spells for delete');
lines.push('  to authenticated');
lines.push('  using (public.is_admin());');
lines.push('');

// --- Lineages insert ---
lines.push('do $$');
lines.push('declare');
lines.push('  rec record;');
lines.push('  v_id int;');
lines.push('  v_race_id int;');
lines.push('  v_subrace_id int;');
lines.push('begin');
lines.push('  for rec in');
lines.push('    select * from (values');
const lineageValues = lineageRows.map((r, i) => {
  const abilityLit = r.ability_bonuses ? lit(JSON.stringify(r.ability_bonuses)) + '::jsonb' : 'null::jsonb';
  return `      (${lit(r.id_temp)}, ${lit(r.race_name)}, ${litOrNull(r.subrace_name)}, ${lit(r.lineage_group)}, ${r.grants_ability_bonus}, ${abilityLit}, ${litOrNull(r.damage_type)}, ${litOrNull(r.resistance_damage_type)}, ${lit(r.source_book)}, ${lit(r.name_fr)}, ${lit(r.mechanical_effect)})${i < lineageRows.length - 1 ? ',' : ''}`;
});
lines.push(lineageValues.join('\n'));
lines.push('    ) as t(id_temp, race_name, subrace_name, lineage_group, grants_ability_bonus, ability_bonuses, damage_type, resistance_damage_type, source_book, name_fr, mechanical_effect)');
lines.push('  loop');
lines.push('    select r.id into v_race_id from public.races r');
lines.push("    join public.translations t on t.entity_type = 'race' and t.entity_id = r.id::text and t.field_name = 'name' and t.locale = 'fr'");
lines.push('    where t.value = rec.race_name;');
lines.push('    if v_race_id is null then');
lines.push("      raise exception 'Race introuvable pour la lignée % : %', rec.id_temp, rec.race_name;");
lines.push('    end if;');
lines.push('');
lines.push('    v_subrace_id := null;');
lines.push('    if rec.subrace_name is not null then');
lines.push('      select s.id into v_subrace_id from public.subraces s');
lines.push("      join public.translations t on t.entity_type = 'subrace' and t.entity_id = s.id::text and t.field_name = 'name' and t.locale = 'fr'");
lines.push('      where s.race_id = v_race_id and t.value = rec.subrace_name;');
lines.push('      if v_subrace_id is null then');
lines.push("        raise exception 'Sous-race introuvable pour la lignée % : %', rec.id_temp, rec.subrace_name;");
lines.push('      end if;');
lines.push('    end if;');
lines.push('');
lines.push('    if not exists (');
lines.push('      select 1 from public.race_lineages rl');
lines.push("      join public.translations n on n.entity_type = 'race_lineage' and n.entity_id = rl.id::text and n.field_name = 'name' and n.locale = 'fr'");
lines.push('      where rl.race_id = v_race_id and n.value = rec.name_fr');
lines.push('    ) then');
lines.push('      insert into public.race_lineages (race_id, subrace_id, lineage_group, grants_ability_bonus, ability_bonuses, damage_type, resistance_damage_type, source_book)');
lines.push('        values (v_race_id, v_subrace_id, rec.lineage_group, rec.grants_ability_bonus, rec.ability_bonuses, rec.damage_type, rec.resistance_damage_type, rec.source_book)');
lines.push('        returning id into v_id;');
lines.push('      insert into public.translations (entity_type, entity_id, field_name, locale, value) values');
lines.push("        ('race_lineage', v_id::text, 'name', 'fr', rec.name_fr),");
lines.push("        ('race_lineage', v_id::text, 'mechanical_effect', 'fr', rec.mechanical_effect);");
lines.push('    end if;');
lines.push('  end loop;');
lines.push('end $$;');
lines.push('');

// --- Innate spells insert ---
lines.push('do $$');
lines.push('declare');
lines.push('  rec record;');
lines.push('  v_id int;');
lines.push('  v_race_id int;');
lines.push('  v_subrace_id int;');
lines.push('  v_lineage_id int;');
lines.push('  v_spell_id int;');
lines.push('begin');
lines.push('  for rec in');
lines.push('    select * from (values');
const lineageNameByIdTemp = Object.fromEntries(lineageRows.map((r) => [r.id_temp, r.name_fr]));
const spellValues = spellRows.map((r, i) => {
  const lineageName = r.lineage_id_temp ? lineageNameByIdTemp[r.lineage_id_temp] : null;
  if (r.lineage_id_temp && !lineageName) throw new Error('No lineage name for id_temp ' + r.lineage_id_temp);
  return `      (${lit(r.race_name)}, ${litOrNull(r.subrace_name)}, ${litOrNull(lineageName)}, ${litOrNull(r.spell_name)}, ${litOrNull(r.unresolved_note)}, ${r.character_level}, ${lit(r.ability_used_for_dc)})${i < spellRows.length - 1 ? ',' : ''}`;
});
lines.push(spellValues.join('\n'));
lines.push('    ) as t(race_name, subrace_name, lineage_name, spell_name, unresolved_note, character_level, ability_used_for_dc)');
lines.push('  loop');
lines.push('    select r.id into v_race_id from public.races r');
lines.push("    join public.translations t on t.entity_type = 'race' and t.entity_id = r.id::text and t.field_name = 'name' and t.locale = 'fr'");
lines.push('    where t.value = rec.race_name;');
lines.push('    if v_race_id is null then');
lines.push("      raise exception 'Race introuvable pour un sort inné : %', rec.race_name;");
lines.push('    end if;');
lines.push('');
lines.push('    v_subrace_id := null;');
lines.push('    if rec.subrace_name is not null then');
lines.push('      select s.id into v_subrace_id from public.subraces s');
lines.push("      join public.translations t on t.entity_type = 'subrace' and t.entity_id = s.id::text and t.field_name = 'name' and t.locale = 'fr'");
lines.push('      where s.race_id = v_race_id and t.value = rec.subrace_name;');
lines.push('      if v_subrace_id is null then');
lines.push("        raise exception 'Sous-race introuvable pour un sort inné : %', rec.subrace_name;");
lines.push('      end if;');
lines.push('    end if;');
lines.push('');
lines.push('    v_lineage_id := null;');
lines.push('    if rec.lineage_name is not null then');
lines.push('      -- lineage_name porte directement le nom fr de la lignée (résolu côté script Node)');
lines.push('      select rl.id into v_lineage_id from public.race_lineages rl');
lines.push("      join public.translations n on n.entity_type = 'race_lineage' and n.entity_id = rl.id::text and n.field_name = 'name' and n.locale = 'fr'");
lines.push('      where rl.race_id = v_race_id and n.value = rec.lineage_name;');
lines.push('      if v_lineage_id is null then');
lines.push("        raise exception 'Lignée introuvable pour un sort inné : %', rec.lineage_name;");
lines.push('      end if;');
lines.push('    end if;');
lines.push('');
lines.push('    v_spell_id := null;');
lines.push('    if rec.spell_name is not null then');
lines.push('      select sp.id into v_spell_id from public.spells sp');
lines.push("      join public.translations t on t.entity_type = 'spell' and t.entity_id = sp.id::text and t.field_name = 'name' and t.locale = 'fr'");
lines.push('      where t.value = rec.spell_name;');
lines.push('      if v_spell_id is null then');
lines.push("        raise exception 'Sort introuvable : %', rec.spell_name;");
lines.push('      end if;');
lines.push('    end if;');
lines.push('');
lines.push('    if not exists (');
lines.push('      select 1 from public.racial_innate_spells ris');
lines.push('      where ris.race_id = v_race_id');
lines.push('        and ris.subrace_id is not distinct from v_subrace_id');
lines.push('        and ris.lineage_id is not distinct from v_lineage_id');
lines.push('        and ris.spell_id is not distinct from v_spell_id');
lines.push('        and ris.character_level = rec.character_level');
lines.push('        and ris.ability_used_for_dc = rec.ability_used_for_dc');
lines.push('    ) then');
lines.push('      insert into public.racial_innate_spells (race_id, subrace_id, lineage_id, spell_id, character_level, ability_used_for_dc)');
lines.push('        values (v_race_id, v_subrace_id, v_lineage_id, v_spell_id, rec.character_level, rec.ability_used_for_dc)');
lines.push('        returning id into v_id;');
lines.push('      if rec.unresolved_note is not null then');
lines.push('        insert into public.translations (entity_type, entity_id, field_name, locale, value) values');
lines.push("          ('racial_innate_spell', v_id::text, 'unresolved_note', 'fr', rec.unresolved_note);");
lines.push('      end if;');
lines.push('    end if;');
lines.push('  end loop;');
lines.push('end $$;');
lines.push('');

fs.writeFileSync('lot3_migration.sql', lines.join('\n'), 'utf-8');
console.log('written. lineage rows:', lineageRows.length, 'spell rows:', spellRows.length);
